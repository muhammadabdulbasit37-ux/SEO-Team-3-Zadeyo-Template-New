/** Netlify-style redirect rules for static hosts (copied to dist via public/). */
import fs from 'node:fs';
import path from 'node:path';
import { PATH_REDIRECTS } from './redirects.mjs';
import { CHECKOUT_PATH_REDIRECTS } from '../src/config/checkout-redirects.mjs';
import { SITE_URL } from '../src/config/site-url.mjs';
import { SECURITY_HEADERS } from '../src/config/security-headers.mjs';

// Shared headers appear once: overlapping Pages rules otherwise append duplicate policies.
// Worker/Pages handlers set document/checkout caching before the static server is reached.
const headerLines = ['# Generated by scripts/generate-static-redirects.mjs. Do not edit.', '/*'];
for (const [name, value] of Object.entries(SECURITY_HEADERS)) headerLines.push(`  ${name}: ${value}`);
const cacheRules = [
  ['/robots.txt', 'public, max-age=3600, must-revalidate'],
  ...['/rss.xml', '/sitemap.xml', '/sitemap.xsl', '/site.webmanifest'].map(route => [route, 'public, max-age=86400']),
  ...['/_astro/*', '/images/*', '/favicon*', '/apple-touch-icon.png'].map(route => [route, 'public, max-age=31536000, immutable']),
  ...['/404', '/404.html', '/es/404/', '/de/404/', '/fr/404/', '/go/*', '/es/go/*', '/de/go/*', '/fr/go/*'].map(route => [route, 'no-store']),
];
for (const [route, cache] of cacheRules) {
  headerLines.push('', route, `  Cache-Control: ${cache}`);
  if (cache === 'no-store') headerLines.push('  X-Robots-Tag: noindex, follow');
}
fs.writeFileSync(path.join('public', '_headers'), headerLines.join('\n') + '\n');
console.log('Wrote shared security/cache policies → public/_headers');

const lines = ['# Generated by scripts/generate-static-redirects.mjs. Do not edit.'];
for (const [from, to] of PATH_REDIRECTS.entries()) {
  lines.push(`${from}  ${to}  301`);
}
// Checkout must run through Worker/Pages or the query-preserving HTML fallback below.
// A static redirect to a destination that already has ?to= can discard ?plan=.

const out = path.join('public', '_redirects');
fs.writeFileSync(out, `${lines.join('\n')}\n`);
console.log(`Wrote ${lines.length - 1} redirect rules → ${out}`);

const robots = `User-agent: *
Allow: /
Disallow: /go/
Disallow: /es/go/
Disallow: /de/go/
Disallow: /fr/go/

Sitemap: ${SITE_URL}/sitemap.xml
`;
fs.writeFileSync(path.join('public', 'robots.txt'), robots);
console.log(`Wrote public/robots.txt → Sitemap: ${SITE_URL}/sitemap.xml`);

// Retired clone-only fallback: it is not one of this site's configured checkout paths.
const retiredCheckoutFile = path.join('public', 'go', 'mw4-cheats', 'index.html');
if (fs.existsSync(retiredCheckoutFile)) fs.unlinkSync(retiredCheckoutFile);

/** Fallback pages when a host serves files instead of `_redirects`. Hover still shows `/go/…`. */
function escapeHtml(value) {
  return value.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
}

const GO_PAGE_COPY = {
  '/go/the-isle-cheats/': {
    title: 'Continue to The Isle Cheats checkout',
    description: 'Continue to our external checkout for The Isle Cheats.',
    h1: 'Continue to The Isle Cheats',
    h2: 'The Isle Cheats checkout',
  },
  '/go/wardogs/': {
    title: 'Continue to The Isle Cheats alternate checkout',
    description:
      'This noindex page is an alternate checkout path for The Isle Cheats. It is not listed in search.',
    h1: 'Continue on the alternate checkout path',
    h2: 'Partner checkout on the alternate path',
  },
  '/go/hwid-spoofer/': {
    title: 'Continue to HWID Spoofer checkout',
    description:
      'This noindex page sends you to partner checkout for the HWID Spoofer. It is not listed in search.',
    h1: 'Continue to HWID Spoofer checkout',
    h2: 'Partner checkout for the HWID Spoofer',
  },
  '/go/skin-changer/': {
    title: 'Continue to Skin Changer checkout',
    description:
      'This noindex page sends you to partner checkout for the Skin Changer. It is not listed in search.',
    h1: 'Continue to Skin Changer checkout',
    h2: 'Partner checkout for the Skin Changer',
  },
  '/go/ugc/': {
    title: 'Continue to the UGC checkout page',
    description:
      'This noindex page sends you to partner checkout for UGC recovery tools. It is not listed in search.',
    h1: 'Continue to the UGC checkout page',
    h2: 'Partner checkout for UGC recovery',
  },
};

let checkoutPages = 0;
for (const [from, to] of CHECKOUT_PATH_REDIRECTS.entries()) {
  if (!from.endsWith('/')) continue;
  const dir = path.join('public', from);
  fs.mkdirSync(dir, { recursive: true });
  const href = escapeHtml(to);
  const jsUrl = JSON.stringify(to);
  const copy = GO_PAGE_COPY[from];
  const title = escapeHtml(copy.title);
  const description = escapeHtml(copy.description);
  const h1 = escapeHtml(copy.h1);
  const h2 = escapeHtml(copy.h2);
  fs.writeFileSync(
    path.join(dir, 'index.html'),
    `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex, follow">
<title>${title}</title>
<meta name="description" content="${description}">
<noscript><meta http-equiv="refresh" content="0;url=${href}"></noscript>
<script>var dest=${jsUrl};var extra=location.search?location.search.slice(1):"";if(extra)dest+=(dest.indexOf("?")>=0?"&":"?")+extra;location.replace(dest);</script>
</head>
<body>
<h1>${h1}</h1>
<h2>${h2}</h2>
</body>
</html>
`,
  );
  checkoutPages += 1;
}
console.log(`Wrote ${checkoutPages} checkout redirect pages → public/go/`);
